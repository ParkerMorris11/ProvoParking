CREATE SCHEMA IF NOT EXISTS parking_private;
REVOKE ALL ON SCHEMA parking_private FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA parking_private TO authenticated;
CREATE TABLE IF NOT EXISTS parking_private.admin_account (
  auth_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  granted_at timestamptz NOT NULL DEFAULT statement_timestamp()
);
ALTER TABLE parking_private.admin_account ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON parking_private.admin_account FROM PUBLIC, anon, authenticated;
-- No browser role has a policy or table grant. Only trusted SQL can grant/revoke admins.

CREATE TABLE IF NOT EXISTS public.destination (
  destination_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  building_code text NOT NULL UNIQUE CHECK (length(building_code) BETWEEN 1 AND 12),
  name text NOT NULL CHECK (length(name) BETWEEN 1 AND 160),
  latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
  longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
  source_url text NOT NULL,
  verified_on date NOT NULL
);
ALTER TABLE public.destination ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.destination FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.destination TO anon, authenticated;
DROP POLICY IF EXISTS destination_public_read ON public.destination;
CREATE POLICY destination_public_read ON public.destination FOR SELECT TO anon, authenticated USING (true);

ALTER TABLE public.parking_session ADD COLUMN IF NOT EXISTS destination_id integer
  REFERENCES public.destination(destination_id);
CREATE INDEX IF NOT EXISTS parking_session_destination_idx ON public.parking_session(destination_id);
CREATE INDEX IF NOT EXISTS parking_session_user_started_idx ON public.parking_session(user_id, started_at DESC);

CREATE TABLE IF NOT EXISTS public.app_visit (
  visit_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id integer NOT NULL REFERENCES public.app_user(user_id) ON DELETE CASCADE,
  opened_at timestamptz NOT NULL DEFAULT statement_timestamp(),
  open_token uuid NOT NULL,
  UNIQUE(user_id, open_token)
);
CREATE INDEX IF NOT EXISTS app_visit_user_opened_idx ON public.app_visit(user_id, opened_at DESC);
ALTER TABLE public.app_visit ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.app_visit FROM PUBLIC, anon, authenticated;
GRANT INSERT (user_id, open_token) ON public.app_visit TO authenticated;
-- No user can read or modify visit history, or supply a client-chosen timestamp.
DROP POLICY IF EXISTS app_visit_insert_own ON public.app_visit;
CREATE POLICY app_visit_insert_own ON public.app_visit FOR INSERT TO authenticated
  WITH CHECK (user_id IN (SELECT u.user_id FROM public.app_user u WHERE u.auth_id = (SELECT auth.uid())));

CREATE OR REPLACE FUNCTION parking_private.stamp_okr_session()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path = '' AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    NEW.started_at := statement_timestamp();
    -- Older deployed clients may omit destination_id during rollout. Keep parking
    -- working; coverage counts expose these unmeasured sessions. New UI requires it.
  ELSIF NEW.user_id IS DISTINCT FROM OLD.user_id OR NEW.area_id IS DISTINCT FROM OLD.area_id
    OR NEW.destination_id IS DISTINCT FROM OLD.destination_id OR NEW.started_at IS DISTINCT FROM OLD.started_at THEN
    RAISE EXCEPTION 'Session tracking fields cannot be changed' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;
REVOKE ALL ON FUNCTION parking_private.stamp_okr_session() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS stamp_okr_session ON public.parking_session;
CREATE TRIGGER stamp_okr_session BEFORE INSERT OR UPDATE ON public.parking_session
  FOR EACH ROW EXECUTE FUNCTION parking_private.stamp_okr_session();

-- The ONLY cross-user read runs in a private-schema function with an explicit,
-- fresh allowlist check on EVERY call. No identity/permission input is accepted.
CREATE OR REPLACE FUNCTION parking_private.read_okr_metrics()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE result jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT EXISTS (SELECT 1 FROM parking_private.admin_account a WHERE a.auth_id = auth.uid()) THEN
    RAISE EXCEPTION 'Admin access required' USING ERRCODE = '42501';
  END IF;
  WITH users AS MATERIALIZED (
    SELECT u.user_id FROM public.app_user u WHERE u.auth_id IS NOT NULL
      AND NOT EXISTS (SELECT 1 FROM parking_private.admin_account a WHERE a.auth_id = u.auth_id)
  ), sessions AS MATERIALIZED (
    SELECT s.session_id, s.user_id, s.started_at, s.destination_id, a.latitude, a.longitude
    FROM public.parking_session s JOIN users u USING(user_id)
    JOIN public.parking_area a USING(area_id) WHERE NOT a.is_sample_data
  ), distances AS (
    SELECT 3958.7613 * 2 * asin(sqrt(least(1.0, greatest(0.0,
      power(sin(radians((d.latitude - s.latitude)::double precision) / 2), 2)
      + cos(radians(s.latitude::double precision)) * cos(radians(d.latitude))
      * power(sin(radians((d.longitude - s.longitude)::double precision) / 2), 2)
    )))) AS miles FROM sessions s JOIN public.destination d USING(destination_id)
  ), gaps AS (
    SELECT extract(epoch FROM (s.started_at - v.opened_at)) / 60.0 AS minutes
    FROM sessions s CROSS JOIN LATERAL (
      SELECT av.opened_at FROM public.app_visit av WHERE av.user_id = s.user_id
        AND av.opened_at <= s.started_at AND av.opened_at >= s.started_at - interval '1 hour'
      ORDER BY av.opened_at DESC LIMIT 1
    ) v
  ), counts AS (
    SELECT (SELECT count(*) FROM users) AS users,
      (SELECT count(*) FROM public.favorite_area f JOIN users u USING(user_id)) AS favorites
  )
  SELECT jsonb_build_object(
    'measured_at', statement_timestamp(), 'signups', c.users,
    'favorites_count', c.favorites,
    'favorites_average', c.favorites::numeric / nullif(c.users, 0),
    'distance_average_miles', (SELECT avg(miles) FROM distances),
    'parking_average_minutes', (SELECT avg(minutes) FROM gaps),
    'total_sessions', (SELECT count(*) FROM sessions),
    'distance_sessions', (SELECT count(*) FROM distances),
    'parking_sessions', (SELECT count(*) FROM gaps)
  ) INTO result FROM counts c;
  RETURN result;
END;
$$;
REVOKE ALL ON FUNCTION parking_private.read_okr_metrics() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION parking_private.read_okr_metrics() TO authenticated;

-- Invoker-only Data API wrapper. The privileged implementation is not in an exposed schema.
CREATE OR REPLACE FUNCTION public.get_admin_okr_metrics()
RETURNS jsonb LANGUAGE sql SECURITY INVOKER SET search_path = '' AS $$
  SELECT parking_private.read_okr_metrics();
$$;
REVOKE ALL ON FUNCTION public.get_admin_okr_metrics() FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_admin_okr_metrics() TO authenticated;

